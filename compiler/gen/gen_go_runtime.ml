(** Bakes the audited Go runtime into the compiler binary. *)

let find_repo_root start =
  let rec up dir remaining =
    let runtime = Filename.concat dir "runtime/go/teslrt/int.go" in
    if Sys.file_exists runtime then Some dir
    else if remaining = 0 then None
    else
      let parent = Filename.dirname dir in
      if parent = dir then None else up parent (remaining - 1)
  in
  let resolved = try Unix.realpath start with _ -> start in
  up (Filename.dirname resolved) 12

let () =
  let root =
    match find_repo_root Sys.argv.(0) with
    | Some root -> root
    | None ->
      Printf.eprintf "gen_go_runtime: could not locate runtime/go/teslrt/int.go\n";
      exit 2
  in
  let files = ["apitest.go"; "check.go"; "control.go"; "dict.go"; "either.go"; "float.go"; "int.go"; "json.go"; "list.go"; "maybe.go"; "request.go"; "server.go"; "set.go"; "string.go"; "tuple.go"] in
  print_endline "(** Generated by compiler/gen/gen_go_runtime.ml. *)";
  print_endline "let files = [";
  List.iter (fun name ->
    let path = Filename.concat root (Filename.concat "runtime/go/teslrt" name) in
    let content = In_channel.with_open_bin path In_channel.input_all in
    Printf.printf "  (%S, %S);\n" name content) files;
  print_endline "]"
