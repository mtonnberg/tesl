(** Bakes the audited Go runtime into the compiler binary. *)

let find_repo_root start =
  let rec up dir remaining =
    let runtime = Filename.concat dir "runtime/go/teslrt/int.go" in
    if Sys.file_exists runtime then Some dir
    else if remaining = 0 then None
    else
      let parent = Filename.dirname dir in
      if parent = dir then None else up parent (remaining - 1)
  in
  let resolved = try Unix.realpath start with _ -> start in
  up (Filename.dirname resolved) 12

let () =
  let root =
    match find_repo_root Sys.argv.(0) with
    | Some root -> root
    | None ->
      Printf.eprintf "gen_go_runtime: could not locate runtime/go/teslrt/int.go\n";
      exit 2
  in
  let files = ["agent.go"; "agent_endpoint.go"; "agent_provider.go"; "apitest.go"; "apitest_json.go"; "cache.go"; "check.go"; "control.go"; "crypto.go"; "debug.go"; "debug_control.go"; "debug_file_unix.go"; "debug_file_windows.go"; "debug_state.go"; "debug_sql.go"; "debug_value.go"; "dict.go"; "env.go"; "either.go"; "email.go"; "float.go"; "hostclass.go"; "hostname.go"; "httpclient.go"; "httpstub.go"; "int.go"; "int32.go"; "json.go"; "jws.go"; "jwt.go"; "list.go"; "loadtest.go"; "maybe.go"; "money.go"; "currency_data.go"; "database.go"; "dbquery.go"; "postgres.go"; "units.go"; "units_data.go"; "password.go"; "pgpubsub.go"; "pgstores.go"; "prop.go"; "queue.go"; "random.go"; "regex.go"; "request.go"; "result.go"; "secret.go"; "serve.go"; "server.go"; "set.go"; "sse.go"; "sse_http.go"; "sso.go"; "sso_flow.go"; "sso_route.go"; "string.go"; "table.go"; "telemetry.go"; "time.go"; "timetrunc.go"; "timezone.go"; "tuple.go"; "url.go"; "workers.go"] in
  print_endline "(** Generated by compiler/gen/gen_go_runtime.ml. *)";
