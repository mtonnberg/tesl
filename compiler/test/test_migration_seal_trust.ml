let preview_errors errors = String.concat "\n" (List.map (fun (e:Migration_preview.error) -> e.message) errors)
let apply = function
  | Error errors -> fail (preview_errors errors)
  | Ok preview ->
    if not (Migration_preview.compilable preview) then
      fail ("generated revision does not compile:\n" ^ render_diags (Migration_preview.diagnostics preview));
    List.iter (fun (e:Migration_manifest.edit) -> write e.path e.after)
      (Migration_manifest.edits (Migration_preview.manifest preview))

(* V1 {id,name}; V2 adds o2; V3 renames o2 -> r3 with a Contract; V4 (current)
   adds o4. Completed steps: V2 (additive) and V3 (transforming + Contract). *)
let with_history f = with_temp (fun root ->
  let path = Filename.concat root in
  let entry = path "app.tesl" in
  write (path "tesl.toml") "";
  let v1 = ["id","String"; "name","String"] in
  let v2 = v1 @ ["o2","Maybe String"] in
  let v3 = v1 @ ["r3","Maybe String"] in
  let v4 = v3 @ ["o4","Maybe String"] in
  write (path "schema/scale/v-current.tesl") (schema v1);
  write entry app;
  let generate new_revision = Migration_program.with_compilation_cache (fun () ->
    apply (Migration_preview.generate ~project_root:root ~entry_file:entry ~database:None ~new_revision ~documents:[])) in
  let revision version fields body =
    generate true;
    write (path "schema/scale/v-current.tesl") (schema fields);
    let edge = path (Printf.sprintf "migrations/scale/v%d.tesl" version) in
    let header = List.hd (Str.split_delim (Str.regexp_string "module ") (read edge)) in
    write edge (header ^ body);
    generate false in
  revision 2 v2 (additive 2);
  revision 3 v3 (rename 3 v3 ~old:"o2" ~fresh:"r3");
  Migration_program.with_compilation_cache (fun () ->
    apply (Migration_preview.generate_contract ~project_root:root ~entry_file:entry ~database:None ~version:3 ~documents:[]));
  revision 4 v4 (additive 4);
  f root path entry)

(* Rewrite a frozen migration file and recompute its own frozen-source digest, as
   someone editing history and its recorded hash together would. *)
let reseal_closure root file edit =
  let source = edit (read file) in
  let closure = match Migration_closure.capture ~project_root:root ~root_file:file ~source with
    | Ok closure -> closure | Error _ -> fail "recapture frozen closure" in
  match Migration_closure.attach ~file ~source closure with
  | Ok sealed -> write file sealed
  | Error _ -> fail "reattach frozen closure"

let trusted_during f =
  Migration_trust.reset_trusted_roots ();
  let result = f () in
  result, List.sort_uniq compare (Migration_trust.trusted_roots ())

let frozen_files = ["schema/scale/v2.tesl"; "migrations/scale/v2.tesl"; "migrations/scale/v3.tesl";
  "migrations/scale/v3-contract.tesl"; "schema/scale/v3.tesl"]

(* (a) Identity: trusted output equals full-history output. *)
let trusted_equals_full () = with_history (fun _ path entry ->
  let full, full_roots = trusted_during (fun () -> with_full_history true (fun () -> emit entry)) in
  let normal, roots = trusted_during (fun () -> with_full_history false (fun () -> emit entry)) in
  check bool "the history emits" true (String.starts_with ~prefix:"ok\n" full);
  check string "trusted emission is byte-identical to full-history emission" full normal;
  check (list string) "full-history trusts nothing" [] full_roots;
  check (list string) "both completed steps are trusted"
    ["Schema.Scale.Migrate.V2"; "Schema.Scale.Migrate.V3"] roots;
  List.iter (fun name ->
    let file = path name in
    let full = with_full_history true (fun () -> check_file file) in
    let normal = with_full_history false (fun () -> check_file file) in
    check string ("diagnostics for " ^ name) full normal) ("app.tesl" :: "migrations/scale/v4.tesl" :: frozen_files))

(* The checked-in 13-revision example was sealed by an older compiler build, so
   its steps are re-checked (the ABI rule); both modes still agree exactly. *)
let example_equals_full () = with_temp (fun root ->
  let project = Filename.concat root "example" in
  if Sys.command (Filename.quote_command "cp" ["-R"; Filename.concat (repo_root ()) "example/db-migration-example"; project]) <> 0
  then fail "copy example";
  let app = Filename.concat project "todo-app.tesl" in
  let full = with_full_history true (fun () -> emit app) in
  let normal = with_full_history false (fun () -> emit app) in
  check bool "the example emits" true (String.starts_with ~prefix:"ok\n" full);
  check string "example emission is identical in both modes" full normal;
  List.iter (fun name ->
    let file = Filename.concat project name in
    check string ("example diagnostics for " ^ name)
      (with_full_history true (fun () -> check_file file)) (with_full_history false (fun () -> check_file file)))
    ["todo-app.tesl"; "migrations/todo/v5.tesl"; "migrations/todo/v12-contract.tesl"])

(* (b) Any edited byte of a frozen revision still fails, now because its seal
   no longer verifies and the step falls back to the full integrity check. *)
(* Semantics-preserving edits: only the recorded bytes notice them. *)
let edit_string source = replace "\"n\"" "\"m\"" source
let edit_body source = replace "makeAlpha \"fixture\"" "makeAlpha \"fixturf\"" source
let tamper name edit () = with_history (fun _ path entry ->
  let file = path name in
  write file (edit (read file));
  let normal, roots = trusted_during (fun () -> with_full_history false (fun () -> emit entry)) in
  let full = with_full_history true (fun () -> emit entry) in
  check bool ("tampered " ^ name ^ " fails emission") true (String.starts_with ~prefix:"failed\n" normal);
  check bool ("the integrity diagnostic names MIG013:\n" ^ normal) true (contains normal "MIG013");
  check string "the failure equals the full-history failure" full normal;
  let owner = if contains name "v2" then "Schema.Scale.Migrate.V2" else "Schema.Scale.Migrate.V3" in
  check bool "the tampered step is not trusted" false (List.mem owner roots);
  let app_errors = with_full_history false (fun () -> check_errors entry) in
  check bool "application diagnostics report the tampered history" true
    (List.exists (fun (d:Compile.diagnostic) -> d.code = "MIG013") app_errors))

(* (c) A seal recorded by another compiler ABI (same stored-value contract) is
   re-checked under this compiler instead of trusted, and still compiles. *)
let hex s = String.concat "" (List.init (String.length s) (fun i -> Printf.sprintf "%02x" (Char.code s.[i])))
(* Revisions frozen by an older compiler carry no checkpoints (and a checkpoint
   records the history it was derived from), so drop them first. *)
let drop_checkpoints path =
  List.iter (fun version ->
    let file = path (Printf.sprintf "migrations/scale/v%d.tesl" version) in
    let checkpoint = path (Printf.sprintf "migrations/scale/v%d.checkpoint" version) in
    if Sys.file_exists checkpoint then Sys.remove checkpoint;
    write file (Str.global_replace (Str.regexp "# tesl:frozen-checkpoint [0-9a-f]+\n") "" (read file))) [2;3]

let other_abi_is_rechecked () = with_history (fun root path entry ->
  drop_checkpoints path;
  let file = path "migrations/scale/v2.tesl" in
  let abi = Migration_abi.id (Result.get_ok (Migration_abi.current ())) in
  check bool "the generated seal records this compiler" true (contains (read file) (hex abi));
  reseal_closure root file (replace (hex abi) (hex "tesl-source-abi-v1:another-compiler-build"));
  let normal, roots = trusted_during (fun () -> with_full_history false (fun () -> emit entry)) in
  let full = with_full_history true (fun () -> emit entry) in
  check bool "the re-checked history emits" true (String.starts_with ~prefix:"ok\n" normal);
  check string "re-checked output equals full-history output" full normal;
  check (list string) "only the step sealed by this compiler is trusted" ["Schema.Scale.Migrate.V3"] roots;
  check string "application diagnostics stay clean" "" (render_diags (with_full_history false (fun () -> check_errors entry))))

(* (d) The accepted trade-off: a frozen step edited together with consistently
   recomputed digests is trusted by normal compilation; full-history rejects it.
   Querying the edited file directly always checks it completely. *)
let resealed_bad_step () = with_history (fun root path entry ->
  let file = path "migrations/scale/v3.tesl" in
  reseal_closure root file (fun source -> source ^ "fn brokenHelper() -> String = 5\n");
  let normal = with_full_history false (fun () -> check_errors entry) in
  let full = with_full_history true (fun () -> check_errors entry) in
  check string "normal mode trusts the consistently resealed step" "" (render_diags normal);
  check bool "full-history mode rejects the bad step" true (full <> []);
  check bool "a direct query of the edited file checks it completely" true
    (with_full_history false (fun () -> check_errors file) <> []))


(* Within one command the history cache trusts its first verification; a frozen
   byte edited while the command runs is refused by the capture's final source
   guard before the command emits or succeeds. *)
let edit_during_command () = with_history (fun _ path entry ->
  let source = read entry in
  let m = match Parser.parse_module entry source with Parser.Ok m -> m | Parser.Err e -> fail e.msg in
  let file = path "schema/scale/v2.tesl" in
  let result = Migration_program.with_compilation_cache (fun () ->
    Migration_program.with_source_history ~entry:m ~source (fun _ -> write file (edit_string (read file)))) in
  match result with
  | Ok () -> fail "an edit during the command was not caught"
  | Error errors -> check bool "the final guard refuses with MIG013" true
      (List.exists (fun (e:Migration_sparse.error) -> e.code = "MIG013") errors))

let () = run "Migration seal trust" [
  "identity", [
    test_case "trusted output equals full-history output" `Slow trusted_equals_full;
    test_case "13-revision example: both modes identical" `Slow example_equals_full;
  ];
  "integrity", [
    test_case "frozen schema snapshot byte" `Slow (tamper "schema/scale/v2.tesl" edit_string);
    test_case "frozen migration byte" `Slow (tamper "migrations/scale/v3.tesl" edit_body);
    test_case "frozen Contract byte" `Slow (tamper "migrations/scale/v3-contract.tesl" (fun s -> s ^ "\n# edited\n"));
  ];
  "command guard", [ test_case "a frozen edit during one command is refused" `Slow edit_during_command ];
  "abi", [ test_case "another compiler's seal is re-checked" `Slow other_abi_is_rechecked ];
  "trade-off", [ test_case "resealed bad step: trusted normally, rejected in full mode" `Slow resealed_bad_step ];
]
